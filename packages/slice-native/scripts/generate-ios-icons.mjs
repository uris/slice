import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { iconSources, maskSVG } from './ios-icon-source.mjs';

const root = new URL('../', import.meta.url);
const catalog = new URL('platform/ios/Resources/SliceIcons.xcassets/', root);
const icons = await iconSources();
const id = (name) =>
	name === '@'
		? 'atSign'
		: name === ''
			? 'unnamed'
			: name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
if (new Set(icons.map((icon) => id(icon.name))).size !== icons.length) throw new Error('Swift icon names collide');
const assets = icons.flatMap((icon) =>
	icon.variants.map((variant) => ({
		name: icon.name,
		state: variant.state,
		filled: variant.filled,
		asset: `slice-icon-${Buffer.from(icon.name).toString('hex') || 'empty'}-${variant.state}${variant.filled ? '-filled' : ''}`,
		svg: maskSVG(variant.body),
	})),
);
// Render first so a missing browser cannot remove existing generated resources.
const browser = await chromium.launch({ headless: true });
const rendered = [];
try {
	const page = await browser.newPage();
	for (const asset of assets) {
		const images = await page.evaluate(async (svg) => {
			const image = new Image();
			image.src = `data:image/svg+xml;base64,${btoa(svg)}`;
			await image.decode();
			return [1, 2, 3].map((scale) => {
				const canvas = document.createElement('canvas');
				canvas.width = canvas.height = 20 * scale;
				const ctx = canvas.getContext('2d');
				ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
				return canvas.toDataURL('image/png').split(',')[1];
			});
		}, asset.svg);
		rendered.push({ ...asset, images });
	}
} finally {
	await browser.close();
}
const json = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
const info = { author: 'xcode', version: 1 };
mkdirSync(catalog, { recursive: true });
for (const file of readdirSync(catalog))
	if (file.endsWith('.imageset')) rmSync(new URL(file, catalog), { recursive: true });
json(new URL('Contents.json', catalog), { info });
for (const asset of rendered) {
	const folder = new URL(`${asset.asset}.imageset/`, catalog);
	mkdirSync(folder);
	asset.images.forEach((data, i) => writeFileSync(new URL(`icon@${i + 1}x.png`, folder), Buffer.from(data, 'base64')));
	json(new URL('Contents.json', folder), {
		images: [1, 2, 3].map((scale) => ({ idiom: 'universal', filename: `icon@${scale}x.png`, scale: `${scale}x` })),
		info,
		properties: { 'template-rendering-intent': 'template' },
	});
}
json(
	new URL('platform/ios/Resources/SliceIcons.manifest.json', root),
	assets.map(({ svg, ...asset }) => asset),
);
const cases = icons.map((icon) => `    case \`${id(icon.name)}\` = ${JSON.stringify(icon.name)}`).join('\n');
const mappings = assets
	.map(
		(asset) =>
			`        ${JSON.stringify(`${asset.name}|${asset.state}|${asset.filled}`)}: ${JSON.stringify(asset.asset)}`,
	)
	.join(',\n');
writeFileSync(
	new URL('platform/ios/SliceIcons.generated.swift', root),
	`// Generated by scripts/generate-ios-icons.mjs. Do not edit.\nimport UIKit\nimport SwiftUI\n\nprivate final class SliceIconBundleToken {}\n\n/// Parallel native template library; React Native SliceIcon is unchanged.\npublic enum SliceNativeIcon: String, CaseIterable {\n${cases}\n\n    private static let bundle: Bundle = {\n        for container in [Bundle(for: SliceIconBundleToken.self), Bundle.main] {\n            if let url = container.url(forResource: "SliceNativeIcons", withExtension: "bundle"),\n               let bundle = Bundle(url: url) { return bundle }\n        }\n        fatalError("Missing SliceNativeIcons.bundle. Reinstall pods and rebuild the app.")\n    }()\n\n    private static let assets: [String: String] = [\n${mappings}\n    ]\n\n    private func assetName(toggled: Bool, filled: Bool) -> String {\n        let state = toggled && Self.assets["\\(rawValue)|on|false"] != nil ? "on" : "normal"\n        return Self.assets["\\(rawValue)|\\(state)|\\(filled)"]\n            ?? Self.assets["\\(rawValue)|\\(state)|false"]!\n    }\n\n    /// Fixed 1.5-point stroke at a 20-point base size. Optional fills are baked opaque.\n    public func uiImage(toggled: Bool = false, filled: Bool = false) -> UIImage {\n        let name = assetName(toggled: toggled, filled: filled)\n        guard let image = UIImage(named: name, in: Self.bundle, compatibleWith: nil) else {\n            preconditionFailure("Missing Slice icon asset: \\(name)")\n        }\n        return image.withRenderingMode(.alwaysTemplate)\n    }\n\n    public func image(toggled: Bool = false, filled: Bool = false) -> Image {\n        Image(uiImage: uiImage(toggled: toggled, filled: filled)).renderingMode(.template)\n    }\n}\n`,
);
console.log(`Generated ${icons.length} native icons (${assets.length} template variants, 1x/2x/3x).`);
