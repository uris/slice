import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const source = new URL('../src/components/Icon/', root);
const output = new URL('src/components/SliceIcon/', root);
const elements = {
	circle: 'Circle',
	clipPath: 'ClipPath',
	defs: 'Defs',
	g: 'G',
	line: 'Line',
	path: 'Path',
	polygon: 'Polygon',
	polyline: 'Polyline',
	rect: 'Rect',
	use: 'Use',
};
const header = '// Generated by native/scripts/generate-icons.mjs from src/components/Icon. Do not edit directly.\n';
let registry = readFileSync(new URL('iconRegistry.tsx', source), 'utf8');
registry = registry.replace("import type React from 'react';\n", '');
registry = registry.replace("import type { JSX } from 'react';\n", '');
registry = registry.replace(/<(\/?)([a-z][a-zA-Z]*)(?=[\s/>])/g, (match, closing, tag) => {
	if (!elements[tag]) throw new Error(`Unsupported SVG element: ${tag}`);
	return `<${closing}${elements[tag]}`;
});
registry = registry.replace('strokeColor: string;', 'strokeColor: ColorValue;');
registry = registry.replace(/\bxlinkHref=/g, 'href=');
// Empty dash arrays are unnecessary and are not portable across SVG renderers.
registry = registry.replace(/\s+strokeDasharray=""/g, '');
writeFileSync(
	new URL('iconRegistry.tsx', output),
	`${header}import type { JSX } from 'react';\nimport type { ColorValue } from 'react-native';\nimport { ${Object.values(elements).join(', ')} } from 'react-native-svg';\n${registry}`,
);
const types = readFileSync(new URL('_types.ts', source), 'utf8');
const constants = types.slice(types.indexOf('export const SliceIcons ='));
if (!constants.startsWith('export const SliceIcons =')) throw new Error('SliceIcons export was not found');
writeFileSync(new URL('icons.ts', output), header + constants);
