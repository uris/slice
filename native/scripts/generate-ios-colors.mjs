import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
// This module contains only token data; transpile it without importing web runtime code.
const source = readFileSync(new URL('../src/theme/colors/colors.ts', root), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { light, dark } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const excluded = new Set(['surface-shadow-soft', 'surface-shadow-strong']);
const names = Object.keys(light)
	.filter((name) => !excluded.has(name))
	.sort();
if (JSON.stringify(Object.keys(light).sort()) !== JSON.stringify(Object.keys(dark).sort())) {
	throw new Error('Light and dark color token names differ');
}

export function components(value) {
	let rgba;
	if (/^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) {
		rgba = [1, 3, 5].map((offset) => Number.parseInt(value.slice(offset, offset + 2), 16) / 255);
		rgba.push(value.length === 9 ? Number.parseInt(value.slice(7, 9), 16) / 255 : 1);
	} else {
		const match = value.match(/^rgba\(\s*([\d.]+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)\s*\)$/);
		if (!match) throw new Error(`Unsupported color: ${value}`);
		rgba = match
			.slice(1)
			.map(Number)
			.map((v, i) => (i < 3 ? v / 255 : v));
	}
	if (rgba.some((v) => !Number.isFinite(v) || v < 0 || v > 1)) throw new Error(`Invalid color: ${value}`);
	// Xcode treats integer strings as 0–255 components, even for alpha.
	// Keep explicit decimal notation so 1 means fully opaque/full intensity.
	return Object.fromEntries(
		['red', 'green', 'blue', 'alpha'].map((key, i) => {
			const value = String(rgba[i]);
			return [key, value.includes('.') ? value : `${value}.0`];
		}),
	);
}
const catalog = new URL('platform/ios/Resources/SliceColors.xcassets/', root);
const info = { author: 'xcode', version: 1 };
const json = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
// Validate everything before updating generated output.
const entries = names.map((name) => [name, components(light[name]), components(dark[name])]);
mkdirSync(catalog, { recursive: true });
for (const file of readdirSync(catalog)) {
	if (file.endsWith('.colorset')) rmSync(new URL(file, catalog), { recursive: true });
}
json(new URL('Contents.json', catalog), { info });
const identifier = (name) => name.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
const identifiers = names.map(identifier);
if (new Set(identifiers).size !== names.length) throw new Error('Swift color accessor names collide');
for (const [name, any, darkColor] of entries) {
	const folder = new URL(`${name}.colorset/`, catalog);
	mkdirSync(folder);
	json(new URL('Contents.json', folder), {
		colors: [
			{ idiom: 'universal', color: { 'color-space': 'srgb', components: any } },
			{
				idiom: 'universal',
				appearances: [{ appearance: 'luminosity', value: 'dark' }],
				color: { 'color-space': 'srgb', components: darkColor },
			},
		],
		info,
	});
}
writeFileSync(
	new URL('platform/ios/SliceColors.generated.swift', root),
	`// Generated by scripts/generate-ios-colors.mjs. Do not edit.\nimport UIKit\nimport SwiftUI\n\nprivate final class SliceColorBundleToken {}\n\n/// Semantic colors loaded from the SliceNativeColors resource bundle.\npublic enum SliceColors {\n    public static let bundle: Bundle = {\n        let owner = Bundle(for: SliceColorBundleToken.self)\n        for container in [owner, Bundle.main] {\n            if let url = container.url(forResource: "SliceNativeColors", withExtension: "bundle"),\n               let bundle = Bundle(url: url) { return bundle }\n        }\n        fatalError("Missing SliceNativeColors.bundle. Reinstall pods and rebuild the app.")\n    }()\n\n    /// Returns a dynamic UIColor that follows the receiving view's native appearance.\n    public static func uiColor(named name: String) -> UIColor {\n        guard let color = UIColor(named: name, in: bundle, compatibleWith: nil) else {\n            preconditionFailure("Unknown Slice color: \\(name)")\n        }\n        return color\n    }\n\n${names.map((name) => `    public static var ${identifier(name)}: Color { Color("${name}", bundle: bundle) }`).join('\n')}\n}\n\n/// UIKit equivalents of the SwiftUI SliceColors accessors.\npublic enum SliceUIColors {\n${names.map((name) => `    public static var ${identifier(name)}: UIColor { SliceColors.uiColor(named: "${name}") }`).join('\n')}\n}\n`,
);
console.log(`Generated ${names.length} iOS semantic color assets and Swift accessors.`);
